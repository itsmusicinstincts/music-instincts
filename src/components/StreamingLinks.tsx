export default function StreamingLinks({ youtube_url, spotify_url, apple_music_url, soundcloud_url, size = 'md' }: Props) {
  const urls: Record<string, string | undefined> = { youtube_url, spotify_url, apple_music_url, soundcloud_url }
  const available = platforms.filter((p) => urls[p.key])

  if (available.length === 0) return null

  return (
    <div className="flex flex-wrap gap-2">
      {available.map((platform) => (
        <a
          key={platform.key}
          href={urls[platform.key]}
          target="_blank"
          rel="noopener noreferrer"
          className={`streaming-btn text-text-secondary bg-bg-elevated ${platform.color}`}
        >
          {platform.icon}
          {size === 'md' && <span>{platform.label}</span>}
          <ExternalLink size={10} className="opacity-50" />
        </a>
      ))}
    </div>
  )
}
